"""Build the Quay Quest sprite atlas from picks.txt.

Every sprite comes from the pixel-search Hugging Face space
(https://huggingface.co/spaces/cfahlgren1/pixel-search), whose index covers the CC0
dataset Angais/pixel-art-atlas-1.4m. pixel_search.py re-implements the space's query
pipeline over its published data files, so each pick is (query, rank) -> sprite id.

usage: python3 build_atlas.py <space static/data dir> <page cache dir> <work dir>
"""
import base64, io, json, os, re, subprocess, sys
from PIL import Image

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
data, cache, work = sys.argv[1:4]
picks = []
for line in open(f"{here}/picks.txt"):
    line = line.strip()
    if not line or line.startswith("#"): continue
    name, query, rank = [p.strip() for p in line.split("|")]
    picks.append((name, query, int(rank)))
slug = lambda q: re.sub(r"[^a-z0-9]+", "_", q.lower())[:60]
queries = sorted({q for _, q, _ in picks})
missing = [q for q in queries if not os.path.exists(f"{work}/{slug(q)}.json")
           or len(json.load(open(f"{work}/{slug(q)}.json"))["results"]) < 32]
if missing:
    subprocess.run([sys.executable, "-I", f"{here}/pixel_search.py", data, cache, work, "32", *missing], check=True)

COLS = 16
rows = (len(picks) + COLS - 1) // COLS
atlas = Image.new("RGBA", (COLS * 16, rows * 16), (0, 0, 0, 0))
index, credits = {}, []
for i, (name, query, rank) in enumerate(picks):
    meta = json.load(open(f"{work}/{slug(query)}.json"))["results"][rank]
    raw = open(f"{work}/{slug(query)}.rgba", "rb").read()[rank * 1024:(rank + 1) * 1024]
    atlas.paste(Image.frombytes("RGBA", (16, 16), raw), ((i % COLS) * 16, (i // COLS) * 16))
    index[name] = i
    credits.append({"name": name, "query": query, "rank": rank, "sprite_id": meta["id"],
                    "subject": meta["subject"], "caption": meta["caption"]})
os.makedirs(f"{root}/assets", exist_ok=True)
atlas.save(f"{root}/assets/atlas.png", optimize=True)
buf = io.BytesIO(); atlas.save(buf, "PNG", optimize=True)
with open(f"{root}/js/atlas.js", "w") as f:
    f.write("// GENERATED by tools/build_atlas.py - do not edit. 16x16 sprites, %d columns.\n" % COLS)
    f.write("window.QQ = window.QQ || {};\n")
    f.write("QQ.ATLAS_COLS = %d;\n" % COLS)
    f.write("QQ.SPRITES = %s;\n" % json.dumps(index, separators=(",", ":")))
    f.write('QQ.ATLAS_SRC = "data:image/png;base64,%s";\n' % base64.b64encode(buf.getvalue()).decode())
json.dump(credits, open(f"{root}/assets/sprites.json", "w"), indent=1)
print(f"{len(picks)} sprites -> atlas {atlas.size}, png {len(buf.getvalue())} bytes")
